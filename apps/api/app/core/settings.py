"""Application settings.

All configuration is environment-driven. Secrets are never committed; `.env.example`
documents every variable. Settings are cached so the process reads the environment once.
"""

from __future__ import annotations

from functools import lru_cache
from pathlib import Path

from pydantic import Field, field_validator
from pydantic_settings import BaseSettings, SettingsConfigDict

ROOT = Path(__file__).resolve().parents[3]
# <repo>/.env holds global settings; the API's own file (next to this package) holds runtime
# secrets such as APP_ENCRYPTION_KEY. Later files win, so both layouts keep working.
APP_ROOT = Path(__file__).resolve().parents[1]
_API_ENV = ROOT / "api" / ".env"
# Actual repository root — used to locate sibling services (media-engine, web).
REPO_ROOT = ROOT.parent


class Settings(BaseSettings):
    model_config = SettingsConfigDict(
        env_file=(ROOT / ".env", _API_ENV, APP_ROOT / ".env"),
        env_file_encoding="utf-8",
        extra="ignore",
    )

    # --- runtime -----------------------------------------------------------
    app_name: str = "Factory API"
    environment: str = Field(default="development", alias="ENVIRONMENT")
    debug: bool = False
    api_prefix: str = "/api/v1"
    web_origin: str = "http://localhost:3000"

    # --- database / cache --------------------------------------------------
    database_url: str = "sqlite+aiosqlite:///./factory.db"
    redis_url: str | None = None

    # --- auth --------------------------------------------------------------
    jwt_secret: str = "change-me-in-production-please-32-chars"
    jwt_algorithm: str = "HS256"
    access_token_ttl_minutes: int = 60 * 12
    session_cookie_name: str = "factory_session"
    cookie_secure: bool = False
    bootstrap_admin_email: str = "admin@factory.app"
    bootstrap_admin_password: str = "factory-admin-2026"
    bootstrap_admin_name: str = "Operator"

    # --- encryption --------------------------------------------------------
    # AES-256-GCM master key for provider credentials: 64 hex chars or 32 base64 bytes.
    # Generated by `python -m app.cli gen-key`. ``credential_key`` is the legacy name and is
    # only read when APP_ENCRYPTION_KEY is unset.
    app_encryption_key: str = ""
    credential_key: str = ""

    # --- text to speech ----------------------------------------------------
    voice_max_chars: int = 12000  # per narration asset before chunked generation kicks in
    tts_connect_timeout_s: float = 10.0
    tts_request_timeout_s: float = 120.0
    tts_max_attempts: int = 3

    # --- remotion video engine ---------------------------------------------
    remotion_dir: str = ""  # services/media-engine/remotion (auto-detected when empty)
    node_path: str = "node"  # Node 18+; Remotion 4 requires 18 or newer
    remotion_concurrency: int = 0  # 0 = let Remotion decide (half the CPU threads)
    remotion_gl: str = "angle"  # chromium gl backend: angle | swangle | swiftshader | egl
    remotion_crf: int = 20
    remotion_jpeg_quality: int = 90
    remotion_render_timeout_s: int = 1800  # hard ceiling for one render job
    remotion_preview_stills: int = 4  # frames rendered for the dashboard preview
    remotion_license_key: str | None = None  # optional Remotion Company License
    remotion_license_acknowledged: bool = False  # operator confirms their licence tier

    # --- render queue -----------------------------------------------------------
    render_concurrency: int = 1  # simultaneous RenderJobs (each render is already multi-threaded)
    render_max_attempts: int = 2  # automatic retries for transient infrastructure failures
    render_in_api: bool = True  # run the render queue in the API process; false = worker only
    render_cross_process_poll: bool = True  # also pick up jobs queued by another process

    # --- storage -----------------------------------------------------------
    storage_backend: str = "local"  # local | r2
    storage_root: Path = ROOT / "storage"
    r2_account_id: str | None = None
    r2_access_key_id: str | None = None
    r2_secret_access_key: str | None = None
    r2_bucket: str | None = None
    r2_public_base_url: str | None = None

    # --- providers (optional; DB-configured providers take precedence) -----
    default_llm_provider: str = "mock"  # mock | openai | gemini
    openai_api_key: str | None = None
    openai_base_url: str = "https://api.openai.com/v1"
    gemini_api_key: str | None = None
    cartesia_api_key: str | None = None
    elevenlabs_api_key: str | None = None

    # --- workflow ----------------------------------------------------------
    workflow_backend: str = "local"  # local | temporal
    temporal_host: str = "localhost:7233"
    temporal_namespace: str = "default"
    temporal_task_queue: str = "factory-production"
    max_concurrent_workflows: int = 3
    scheduler_enabled: bool = True
    scheduler_poll_seconds: int = 30

    # --- media -------------------------------------------------------------
    ffmpeg_path: str = "ffmpeg"
    ffprobe_path: str = "ffprobe"
    whisper_model: str = "base"

    # --- youtube -----------------------------------------------------------
    google_client_id: str | None = None
    google_client_secret: str | None = None
    google_oauth_redirect: str = "http://localhost:8000/api/v1/youtube/callback"

    # --- limits ------------------------------------------------------------
    rate_limit_per_minute: int = 240
    max_upload_mb: int = 25

    @field_validator("storage_root", mode="before")
    @classmethod
    def _resolve_root(cls, v: object) -> object:
        if isinstance(v, str):
            p = Path(v)
            return p if p.is_absolute() else (ROOT / p).resolve()
        return v

    @property
    def is_production(self) -> bool:
        return self.environment == "production"


@lru_cache
def get_settings() -> Settings:
    return Settings()
